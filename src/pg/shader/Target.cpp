// --- Assembly ----------------------------------------------------------------

bool Assembly::fragmentUses(const std::string& g) const { return contains(fragment.globals, g); }
bool Assembly::vertexUses(const std::string& g) const { return contains(vertex.globals, g); }
bool Assembly::hasVarying(const std::string& v) const { return contains(varyings, v); }

// --- Target ------------------------------------------------------------------

std::string Target::typeName(Type t) const { return pg::shader::typeName(t); }

std::string Target::translate(const std::string& neutralCode) const { return neutralCode; }

std::string Target::construct(Type t, const std::vector<std::string>& args) const {
    return typeName(t) + "(" + join(args, ", ") + ")";
}

std::string Target::splat(Type t, const std::string& scalar) const {
    return typeName(t) + "(" + scalar + ")";
}

std::string Target::convert(const std::string& expr, Type from, Type to) const {
    if (from == to || !isNumeric(from) || !isNumeric(to)) return expr;
    const int have = componentCount(from), want = componentCount(to);
    if (have == 1) return splat(to, expr);
    if (want < have) {
        const bool simple = std::all_of(expr.begin(), expr.end(), isIdentChar);
        return (simple ? expr : "(" + expr + ")") + "." + std::string("xyzw").substr(0, static_cast<size_t>(want));
    }
    std::vector<std::string> args{expr};
    for (int i = have; i < want; ++i) args.push_back(i == 3 ? "1.0" : "0.0");
    return construct(to, args);
}

std::string Target::literal(const Value& v, Type t) const {
    const Value x = v.as(t);
    const int n = componentCount(t);
    if (n <= 1) {
        const std::string s = formatFloat(x.v[0]);
        return s[0] == '-' ? "(" + s + ")" : s;  // safe next to a binary minus
    }
    std::vector<std::string> args;
    for (int i = 0; i < n; ++i) args.push_back(formatFloat(x.v[static_cast<size_t>(i)]));
    return construct(t, args);
}

// --- registry ----------------------------------------------------------------

TargetRegistry::TargetRegistry() {
    add(makeGlsl330Target());
    add(makeGles300Target());
    add(makeVulkanTarget());
    add(makeHlslTarget());
}

TargetRegistry& TargetRegistry::instance() {
    static TargetRegistry r;
    return r;
}

void TargetRegistry::add(std::unique_ptr<Target> target) {
    if (!target) return;
    for (auto& t : targets_) {
        if (t->name() == target->name()) {
            t = std::move(target);
            return;
        }
    }
    targets_.push_back(std::move(target));
}

const Target* TargetRegistry::find(const std::string& name) const {
    for (const auto& t : targets_) {
        if (t->name() == name) return t.get();
    }
    return nullptr;
}

std::vector<const Target*> TargetRegistry::all() const {
    std::vector<const Target*> out;
    for (const auto& t : targets_) out.push_back(t.get());
    return out;
}

std::unique_ptr<Target> makeGlsl330Target() {
    return std::make_unique<GlslTarget>(GlslTarget::Flavor::Gl330);
}
std::unique_ptr<Target> makeGles300Target() {
    return std::make_unique<GlslTarget>(GlslTarget::Flavor::Es300);
}
std::unique_ptr<Target> makeVulkanTarget() {
    return std::make_unique<GlslTarget>(GlslTarget::Flavor::Vulkan);
}
std::unique_ptr<Target> makeHlslTarget() { return std::make_unique<HlslTarget>(); }


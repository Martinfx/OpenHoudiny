// GLSL: OpenGL 3.3 core, OpenGL ES 3.0, and Vulkan (GLSL 450 -> SPIR-V).
// ---------------------------------------------------------------------------

class GlslTarget : public Target {
public:
    enum class Flavor { Gl330, Es300, Vulkan };
    explicit GlslTarget(Flavor f) : flavor_(f) {}

    std::string name() const override {
        switch (flavor_) {
            case Flavor::Gl330:  return "glsl330";
            case Flavor::Es300:  return "gles300";
            case Flavor::Vulkan: return "vulkan";
        }
        return "?";
    }

    std::string description() const override {
        switch (flavor_) {
            case Flavor::Gl330:  return "OpenGL 3.3 core (GLSL 330)";
            case Flavor::Es300:  return "OpenGL ES 3.0 / WebGL 2 (GLSL ES 300)";
            case Flavor::Vulkan: return "Vulkan (GLSL 450, compile to SPIR-V)";
        }
        return "?";
    }

    std::vector<ShaderFile> assemble(const Assembly& a) const override {
        return {file(a, Stage::Vertex), file(a, Stage::Fragment)};
    }

private:
    bool vulkan() const { return flavor_ == Flavor::Vulkan; }

    ShaderFile file(const Assembly& a, Stage stage) const {
        const bool vs = stage == Stage::Vertex;
        const StageBody& body = vs ? a.vertex : a.fragment;
        std::ostringstream o;

        switch (flavor_) {
            case Flavor::Gl330:  o << "#version 330 core\n"; break;
            case Flavor::Es300:  o << "#version 300 es\n"; break;
            case Flavor::Vulkan: o << "#version 450\n"; break;
        }
        o << "// " << kHeader << "\n// Target: " << description() << ", " << stageName(stage)
          << " stage.\n\n";
        if (flavor_ == Flavor::Es300) o << "precision highp float;\n\n";

        uniforms(o, a, body, vs);
        interface(o, a, vs);

        for (const auto& f : body.functions) o << f << '\n';

        o << "void main()\n{\n";
        if (vs) vertexMain(o, a, body);
        else fragmentMain(o, a, body);
        o << "}\n";
        return ShaderFile{vs ? ".vert" : ".frag", o.str(), {{stage, "main"}}};
    }

    void uniforms(std::ostringstream& o, const Assembly& a, const StageBody& body, bool vs) const {
        if (vulkan()) {
            // Vulkan has no loose uniforms: everything numeric lives in one
            // std140 block shared by both stages. The offsets are what the
            // application's struct must match.
            o << "layout(set = 0, binding = 0, std140) uniform Globals\n{\n";
            int cursor = 0;
            auto member = [&](const std::string& type, const std::string& name) {
                int align = 0, size = 0;
                std140(type, align, size);
                cursor = (cursor + align - 1) / align * align;
                o << "    " << type << ' ' << name << ";  // offset " << cursor << '\n';
                cursor += size;
            };
            for (const auto& b : kBuiltins) member(b.glslType, b.name);
            for (const auto& u : a.uniforms) {
                if (u.type != Type::Sampler2D) member(typeName(u.type), u.name);
            }
            o << "};  // " << cursor << " bytes\n";
            for (const auto& u : a.uniforms) {
                if (u.type == Type::Sampler2D && contains(body.uniforms, u.name)) {
                    o << "layout(set = 0, binding = " << (u.binding + 1) << ") uniform sampler2D "
                      << u.name << ";\n";
                }
            }
            o << '\n';
            return;
        }
        bool any = false;
        for (const auto& b : kBuiltins) {
            const bool needed = b.global ? (vs ? a.vertexUses(b.global) : a.fragmentUses(b.global)) : vs;
            if (!needed) continue;
            o << "uniform " << b.glslType << ' ' << b.name << ";\n";
            any = true;
        }
        for (const auto& u : a.uniforms) {
            if (!contains(body.uniforms, u.name)) continue;
            o << "uniform " << typeName(u.type) << ' ' << u.name << ";\n";
            any = true;
        }
        if (any) o << '\n';
    }

    /// Vertex attributes, the vertex -> fragment varyings and the colour output.
    void interface(std::ostringstream& o, const Assembly& a, bool vs) const {
        auto varying = [&](int location, const char* type, const char* name) {
            if (vulkan()) o << "layout(location = " << location << ") ";
            o << (vs ? "out " : "in ") << type << ' ' << name << ";\n";
        };
        if (vs) {
            o << "layout(location = 0) in vec3 a_position;\n";
            if (needsNormal(a)) o << "layout(location = 1) in vec3 a_normal;\n";
            if (needsUv(a)) o << "layout(location = 2) in vec2 a_uv;\n";
        }
        if (a.hasVarying("position")) varying(0, "vec3", "v_position");
        if (a.hasVarying("normal")) varying(1, "vec3", "v_normal");
        if (a.hasVarying("uv")) varying(2, "vec2", "v_uv");
        if (!vs) o << "layout(location = 0) out vec4 o_color;\n";
        o << '\n';
    }

    static bool needsNormal(const Assembly& a) { return a.vertexUses("normal") || a.hasVarying("normal"); }
    static bool needsUv(const Assembly& a) { return a.vertexUses("uv") || a.hasVarying("uv"); }

    void statements(std::ostringstream& o, const StageBody& body) const {
        for (const auto& s : body.statements) {
            o << "    " << typeName(s.type) << ' ' << s.name << " = " << s.expression << ";\n";
        }
    }

    void vertexMain(std::ostringstream& o, const Assembly& a, const StageBody& body) const {
        o << "    vec3 g_position = (u_model * vec4(a_position, 1.0)).xyz;\n";
        if (needsNormal(a)) o << "    vec3 g_normal = normalize(mat3(u_model) * a_normal);\n";
        if (needsUv(a)) o << "    vec2 g_uv = a_uv;\n";
        if (a.vertexUses("view")) o << "    vec3 g_view = normalize(u_cameraPos - g_position);\n";
        if (a.vertexUses("light")) o << "    vec3 g_light = normalize(u_lightDir);\n";
        if (a.vertexUses("time")) o << "    float g_time = u_time;\n";
        statements(o, body);
        if (!body.result.empty()) o << "    g_position += " << body.result << ";\n";
        if (a.hasVarying("position")) o << "    v_position = g_position;\n";
        if (a.hasVarying("normal")) o << "    v_normal = g_normal;\n";
        if (a.hasVarying("uv")) o << "    v_uv = g_uv;\n";
        o << "    gl_Position = u_viewProj * vec4(g_position, 1.0);\n";
    }

    void fragmentMain(std::ostringstream& o, const Assembly& a, const StageBody& body) const {
        if (a.fragmentUses("position")) o << "    vec3 g_position = v_position;\n";
        if (a.fragmentUses("normal")) o << "    vec3 g_normal = normalize(v_normal);\n";
        if (a.fragmentUses("uv")) o << "    vec2 g_uv = v_uv;\n";
        if (a.fragmentUses("view")) o << "    vec3 g_view = normalize(u_cameraPos - v_position);\n";
        if (a.fragmentUses("light")) o << "    vec3 g_light = normalize(u_lightDir);\n";
        if (a.fragmentUses("time")) o << "    float g_time = u_time;\n";
        statements(o, body);
        o << "    o_color = " << body.result << ";\n";
    }

    Flavor flavor_;
};


// HLSL: Direct3D 11/12, shader model 5. One file, two entry points.
// ---------------------------------------------------------------------------

class HlslTarget : public Target {
public:
    std::string name() const override { return "hlsl"; }
    std::string description() const override { return "Direct3D 11/12 (HLSL, shader model 5)"; }

    std::string typeName(Type t) const override {
        switch (t) {
            case Type::Float:     return "float";
            case Type::Vec2:      return "float2";
            case Type::Vec3:      return "float3";
            case Type::Vec4:      return "float4";
            case Type::Sampler2D: return "Texture2D";
            case Type::Any:       return "float";
        }
        return "float";
    }

    std::string translate(const std::string& code) const override {
        static const std::map<std::string, std::string> renames = {
            {"vec2", "float2"},       {"vec3", "float3"},     {"vec4", "float4"},
            {"ivec2", "int2"},        {"ivec3", "int3"},      {"ivec4", "int4"},
            {"bvec2", "bool2"},       {"bvec3", "bool3"},     {"bvec4", "bool4"},
            {"mat2", "float2x2"},     {"mat3", "float3x3"},   {"mat4", "float4x4"},
            {"mix", "lerp"},          {"fract", "frac"},      {"inversesqrt", "rsqrt"},
            {"dFdx", "ddx"},          {"dFdy", "ddy"},        {"mod", "fmod"},
        };
        return renameIdentifiers(code, renames);
    }

    std::string construct(Type t, const std::vector<std::string>& args) const override {
        return typeName(t) + "(" + join(args, ", ") + ")";
    }

    std::string splat(Type t, const std::string& scalar) const override {
        return "((" + typeName(t) + ")(" + scalar + "))";
    }

    std::vector<ShaderFile> assemble(const Assembly& a) const override {
        std::ostringstream o;
        o << "// " << kHeader << "\n// Target: " << description()
          << ". Entry points: vs_main, ps_main.\n\n";

        o << "cbuffer Globals : register(b0)\n{\n";
        for (const auto& b : kBuiltins) o << "    " << b.hlslType << ' ' << b.name << ";\n";
        for (const auto& u : a.uniforms) {
            if (u.type != Type::Sampler2D) o << "    " << typeName(u.type) << ' ' << u.name << ";\n";
        }
        o << "};\n\n";
        bool textures = false;
        for (const auto& u : a.uniforms) {
            if (u.type != Type::Sampler2D) continue;
            o << "Texture2D " << u.name << " : register(t" << u.binding << ");\n";
            o << "SamplerState " << u.name << "_sampler : register(s" << u.binding << ");\n";
            textures = true;
        }
        if (textures) o << '\n';

        const bool normal = a.vertexUses("normal") || a.hasVarying("normal");
        const bool uv = a.vertexUses("uv") || a.hasVarying("uv");
        o << "struct VSInput\n{\n    float3 a_position : POSITION;\n";
        if (normal) o << "    float3 a_normal : NORMAL;\n";
        if (uv) o << "    float2 a_uv : TEXCOORD0;\n";
        o << "};\n\n";
        o << "struct VSOutput\n{\n    float4 position : SV_Position;\n";
        if (a.hasVarying("position")) o << "    float3 v_position : TEXCOORD0;\n";
        if (a.hasVarying("normal")) o << "    float3 v_normal : TEXCOORD1;\n";
        if (a.hasVarying("uv")) o << "    float2 v_uv : TEXCOORD2;\n";
        o << "};\n\n";

        // One file serves both stages, so it carries the helpers of both.
        std::vector<std::string> functions = a.vertex.functions;
        for (const auto& f : a.fragment.functions) {
            if (!contains(functions, f)) functions.push_back(f);
        }
        for (const auto& f : functions) o << f << '\n';

        o << "VSOutput vs_main(VSInput input)\n{\n    VSOutput output;\n";
        o << "    float3 g_position = mul(u_model, float4(input.a_position, 1.0)).xyz;\n";
        if (normal) o << "    float3 g_normal = normalize(mul((float3x3)u_model, input.a_normal));\n";
        if (uv) o << "    float2 g_uv = input.a_uv;\n";
        if (a.vertexUses("view")) o << "    float3 g_view = normalize(u_cameraPos - g_position);\n";
        if (a.vertexUses("light")) o << "    float3 g_light = normalize(u_lightDir);\n";
        if (a.vertexUses("time")) o << "    float g_time = u_time;\n";
        statements(o, a.vertex);
        if (!a.vertex.result.empty()) o << "    g_position += " << a.vertex.result << ";\n";
        if (a.hasVarying("position")) o << "    output.v_position = g_position;\n";
        if (a.hasVarying("normal")) o << "    output.v_normal = g_normal;\n";
        if (a.hasVarying("uv")) o << "    output.v_uv = g_uv;\n";
        o << "    output.position = mul(u_viewProj, float4(g_position, 1.0));\n";
        o << "    return output;\n}\n\n";

        o << "float4 ps_main(VSOutput input) : SV_Target\n{\n";
        if (a.fragmentUses("position")) o << "    float3 g_position = input.v_position;\n";
        if (a.fragmentUses("normal")) o << "    float3 g_normal = normalize(input.v_normal);\n";
        if (a.fragmentUses("uv")) o << "    float2 g_uv = input.v_uv;\n";
        if (a.fragmentUses("view")) {
            o << "    float3 g_view = normalize(u_cameraPos - input.v_position);\n";
        }
        if (a.fragmentUses("light")) o << "    float3 g_light = normalize(u_lightDir);\n";
        if (a.fragmentUses("time")) o << "    float g_time = u_time;\n";
        statements(o, a.fragment);
        o << "    return " << a.fragment.result << ";\n}\n";

        return {ShaderFile{".hlsl", o.str(), {{Stage::Vertex, "vs_main"}, {Stage::Fragment, "ps_main"}}}};
    }

private:
    void statements(std::ostringstream& o, const StageBody& body) const {
        for (const auto& s : body.statements) {
            o << "    " << typeName(s.type) << ' ' << s.name << " = " << s.expression << ";\n";
        }
    }
};


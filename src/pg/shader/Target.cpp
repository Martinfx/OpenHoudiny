std::string renameIdentifiers(const std::string& code,
                              const std::map<std::string, std::string>& renames) {
    std::string out;
    out.reserve(code.size() + code.size() / 8);
    const size_t n = code.size();
    size_t i = 0;
    char lastSignificant = 0;  // last non-space character copied
    auto copy = [&](size_t from, size_t to) {
        out.append(code, from, to - from);
        for (size_t k = to; k > from; --k) {
            if (!std::isspace(static_cast<unsigned char>(code[k - 1]))) {
                lastSignificant = code[k - 1];
                break;
            }
        }
    };
    while (i < n) {
        const char c = code[i];
        if (c == '/' && i + 1 < n && code[i + 1] == '/') {  // line comment
            size_t j = code.find('\n', i);
            j = j == std::string::npos ? n : j;
            copy(i, j);
            i = j;
        } else if (c == '/' && i + 1 < n && code[i + 1] == '*') {  // block comment
            size_t j = code.find("*/", i + 2);
            j = j == std::string::npos ? n : j + 2;
            copy(i, j);
            i = j;
        } else if (isDigit(c) || (c == '.' && i + 1 < n && isDigit(code[i + 1]))) {  // number
            size_t j = i + 1;
            while (j < n && (isIdentChar(code[j]) || code[j] == '.' ||
                             ((code[j] == '+' || code[j] == '-') &&
                              (code[j - 1] == 'e' || code[j - 1] == 'E')))) {
                ++j;
            }
            copy(i, j);
            i = j;
        } else if (isIdentStart(c)) {
            size_t j = i + 1;
            while (j < n && isIdentChar(code[j])) ++j;
            const std::string id = code.substr(i, j - i);
            auto it = renames.find(id);
            if (it != renames.end() && lastSignificant != '.') {
                out += it->second;
                lastSignificant = it->second.back();
            } else {
                copy(i, j);
            }
            i = j;
        } else {
            copy(i, i + 1);
            ++i;
        }
    }
    return out;
}

bool isBuiltinUniform(const std::string& name) {
    return std::any_of(std::begin(kBuiltins), std::end(kBuiltins),
                       [&](const BuiltinUniform& b) { return name == b.name; });
}


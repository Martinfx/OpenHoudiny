bool isIdentStart(char c) { return std::isalpha(static_cast<unsigned char>(c)) || c == '_'; }
bool isIdentChar(char c) { return std::isalnum(static_cast<unsigned char>(c)) || c == '_'; }
bool isDigit(char c) { return std::isdigit(static_cast<unsigned char>(c)) != 0; }

bool contains(const std::vector<std::string>& v, const std::string& s) {
    return std::find(v.begin(), v.end(), s) != v.end();
}

std::string join(const std::vector<std::string>& parts, const char* sep) {
    std::string out;
    for (size_t i = 0; i < parts.size(); ++i) {
        if (i) out += sep;
        out += parts[i];
    }
    return out;
}

const char* kHeader = "Generated by pgshader from a shader graph. Do not edit: edit the graph.";

/// The renderer-owned uniforms, in the order they sit in a uniform block.
struct BuiltinUniform {
    const char* name;
    const char* glslType;
    const char* hlslType;
    const char* global;  ///< the global that needs it, or nullptr if always needed
};
constexpr BuiltinUniform kBuiltins[] = {
    {"u_model", "mat4", "float4x4", nullptr},
    {"u_viewProj", "mat4", "float4x4", nullptr},
    {"u_cameraPos", "vec3", "float3", "view"},
    {"u_time", "float", "float", "time"},
    {"u_lightDir", "vec3", "float3", "light"},
};

/// std140 base alignment and size, in bytes.
void std140(const std::string& glslType, int& align, int& size) {
    if (glslType == "float") { align = 4; size = 4; }
    else if (glslType == "vec2") { align = 8; size = 8; }
    else if (glslType == "vec3") { align = 16; size = 12; }
    else if (glslType == "mat4") { align = 16; size = 64; }
    else { align = 16; size = 16; }  // vec4
}

